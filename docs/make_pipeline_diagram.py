def svg() -> str:
    defs = (
        '<defs>'
        '<marker id="pd-arw" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="6.5" '
        'markerHeight="6.5" orient="auto-start-reverse">'
        '<path d="M0,1 L9,5 L0,9 z" fill="#0f223d"/></marker>'
        '<marker id="pd-arw-sm" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="5.5" '
        'markerHeight="5.5" orient="auto-start-reverse">'
        '<path d="M0,1.6 L9,5 L0,8.4 z" fill="#0f223d"/></marker>'
        '<marker id="pd-arw-teal" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="6.5" '
        'markerHeight="6.5" orient="auto-start-reverse">'
        '<path d="M0,1 L9,5 L0,9 z" fill="#178fa0"/></marker>'
        '</defs>'
    )
    order = [k for k in NODES if NODES[k]["band"] == "main"] + \
            [k for k in NODES if NODES[k]["band"] == "leaf"]
    parts = [
        f'<svg class="pd" viewBox="0 0 {W} {H}" width="100%" role="img" '
        f'aria-label="Pipeline flow chart: reads to a metabolic model and one report" '
        f'xmlns="http://www.w3.org/2000/svg">',
        f"<style>{CSS}</style>",
        defs,
        '<g class="pd-edges">',
        "".join(edge_svg(e) for e in EDGES if e["kind"] != "report"),
        "".join(edge_svg(e) for e in EDGES if e["kind"] == "report"),
        rail_svg(),
        "</g>",
        '<g class="pd-labels">',
        "".join(label_svg(e) for e in EDGES),
        "</g>",
        '<g class="pd-nodes">',
        "".join(node_svg(k, NODES[k]) for k in order),
        bar_svg(),
        "</g>",
        "</svg>",
    ]
    return "".join(parts)


# ------------------------------------------------------------------------ write
def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="validate only")
    ap.add_argument("--stdout", action="store_true", help="print the SVG")
    args = ap.parse_args()

    errs = validate()
    if errs:
        for e in errs:
            print(f"FAIL {e}", file=sys.stderr)
        print(f"{len(errs)} geometry/text problem(s); nothing was written.", file=sys.stderr)
        return 1
    if args.check:
        print(f"OK diagram: {len(NODES)} nodes, {len(EDGES)} edges, no overlaps, "
              f"no edge through a box, every label fits.")
        return 0
    payload = svg()
    if args.stdout:
        print(payload)
        return 0

    text = HTML.read_text(encoding="utf-8")
    block = f"{BEGIN}\n{payload}\n{END}"
    if BEGIN not in text or END not in text:
        print("FAIL the HTML has no diagram markers; add\n"
              f"  {BEGIN}\n  {END}\nwhere the figure belongs.", file=sys.stderr)
        return 1
    new = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block, text, flags=re.S)
    if new != text:
        HTML.write_text(new, encoding="utf-8")
        print(f"wrote {len(payload)} bytes of SVG into {HTML.name}")
    else:
        print("diagram unchanged")
    return 0


