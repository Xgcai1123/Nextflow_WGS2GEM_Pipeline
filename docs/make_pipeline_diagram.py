#!/usr/bin/env python3
"""Render the pipeline flow chart in docs/pipeline-summary.html.

Why a generator instead of hand-placed SVG
------------------------------------------
The previous version of this figure was a hand-drawn ASCII sketch, and it drew an
edge from the raw FASTQ straight into SPAdes -- an edge that does not exist in
`main.nf` (SPADES consumes TRIMMOMATIC's paired output). Nothing checked it, so the
error lived in the document for a while.

So this script does three things:

  1. it declares the graph once, as data (`NODES` / `EDGES`),
  2. it *computes* the geometry (nothing is guessed at by hand),
  3. it *validates* the result before writing anything: every edge must leave the
     bottom/right side of a node and arrive at the top/left side of another, no
     sampled point of any edge may fall inside a node box, no two boxes may
     overlap, and no text may be wider than the box that holds it.

A wrong edge now fails `--check` instead of shipping. The edge list is kept in sync
with `main.nf` by hand-on-review, but the wiring it encodes is transcribed from the
process invocations in `workflow { main: ... }`, not from memory.

Usage
-----
    python3 docs/make_pipeline_diagram.py            # rewrite the block in the HTML
    python3 docs/make_pipeline_diagram.py --check    # validate only, no write
    python3 docs/make_pipeline_diagram.py --stdout   # print the <svg> only
"""

