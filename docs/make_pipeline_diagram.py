# ------------------------------------------------------------------ text metrics
def text_w(s: str, size: float, mono: bool = False, bold: bool = False) -> float:
    """Rough advance width. Deliberately pessimistic -- the check must not pass
    a label that the browser will then overflow."""
    s = re.sub(r"&[a-z]+;", "x", s)          # entities count as one glyph
    if mono:
        per = 0.60
    elif bold:
        per = 0.63
    else:
        per = 0.535
    return len(s) * per * size


# --------------------------------------------------------------------- geometry
def box(node_id: str) -> tuple[float, float, float, float]:
    """(left, top, right, bottom) of a node, or of the MultiQC bar."""
    if node_id == "bar":
        return BAR["x"], BAR["y"], BAR["x"] + BAR["w"], BAR["y"] + BAR["h"]
    n = NODES[node_id]
    w, h = (MAIN_W, MAIN_H) if n["band"] == "main" else (LEAF_W, LEAF_H)
    cy = MAIN_CY if n["band"] == "main" else LEAF_CY
    return n["x"] - w / 2, cy - h / 2, n["x"] + w / 2, cy + h / 2


def anchors(node_id: str):
    left, top, right, bottom = box(node_id)
    cx = (left + right) / 2
    return dict(cx=cx, cy=(top + bottom) / 2, top=top, bottom=bottom,
                left=left, right=right)


def edge_path(e: dict) -> tuple[list[tuple[float, float]], str]:
    """Return (sample points, path 'd') for one edge."""
    a, b = e["src"], e["dst"]
    kind = e["kind"]

    if kind == "report" and a == "rail":                      # bus -> MULTIQC
        pts = [(700, RAIL_Y), (700, BAR["y"])]
        return pts, f"M{pts[0][0]},{pts[0][1]} L{pts[1][0]},{pts[1][1]}"

    if kind == "report" and a == "carve":                     # right-hand channel
        A = anchors(a)
        pts = [(A["right"], A["cy"]), (CHANNEL_X, A["cy"]), (CHANNEL_X, RAIL_Y)]
        return pts, rounded(pts, 12)

    if kind == "report":                                      # leaf -> bus, straight
        A = anchors(a)
        pts = [(A["cx"], A["bottom"]), (A["cx"], RAIL_Y)]
        return pts, f"M{pts[0][0]},{pts[0][1]} L{pts[1][0]},{pts[1][1]}"

    if kind == "order":                                       # arc above both boxes
        A, B = anchors(a), anchors(b)
        x1, y1 = A["right"] - 16, A["top"]
        x2, y2 = B["left"] + 16, B["top"]
        cxp, cyp = (x1 + x2) / 2, y1 - 30
        d = f"M{x1},{y1} Q{cxp},{cyp} {x2},{y2}"
        pts = [(quad(y1, cyp, y2, t), quad(x1, cxp, x2, t)) for t in steps()]
        return [(px, py) for py, px in pts], d

    A, B = anchors(a), anchors(b)
    if abs(A["cy"] - B["cy"]) < 1:                            # same band, left -> right
        pts = [(A["right"], A["cy"]), (B["left"], B["cy"])]
        return pts, f"M{pts[0][0]},{pts[0][1]} L{pts[1][0]},{pts[1][1]}"

    # cross-band: fork out of the bottom edge and curve into the top edge
    x1, y1 = A["cx"], A["bottom"]
    x2, y2 = B["cx"], B["top"]
    dy = (y2 - y1) * 0.55
    d = f"M{x1},{y1} C{x1},{y1 + dy} {x2},{y2 - dy} {x2},{y2}"
    pts = [(x1 + (x2 - x1) * t, bezier(y1, y1 + dy, y2 - dy, y2, t)) for t in steps()]
    return pts, d


def bar_left() -> float:
    return CHANNEL_X                    # CarveMe joins the bus at its right end


def bezier(p0: float, p1: float, p2: float, p3: float, t: float) -> float:
    u = 1 - t
    return u ** 3 * p0 + 3 * u * u * t * p1 + 3 * u * t * t * p2 + t ** 3 * p3


def quad(p0: float, p1: float, p2: float, t: float) -> float:
    u = 1 - t
    return u * u * p0 + 2 * u * t * p1 + t * t * p2


def steps():
    return [i / 240 for i in range(241)]


def rounded(pts, r):
    def seg(p, q):
        return f"L{q[0]},{q[1]}"
    d = f"M{pts[0][0]},{pts[0][1]}"
    for i in range(1, len(pts) - 1):
        p, q, n = pts[i - 1], pts[i], pts[i + 1]
        d += f" L{cx_ok(p, q, r)},{cy_ok(p, q, r)}"
        d += f" Q{q[0]},{q[1]} {cx_ok(q, n, r)},{cy_ok(q, n, r)}"
    d += seg(pts[-1], pts[-1])
    return d


def cx_ok(p, q, r):
    dx = q[0] - p[0]
    L = abs(dx) or 1
    return q[0] - (r if dx > 0 else -r) * min(1.0, L / r) if abs(dx) > r else q[0]


def cy_ok(p, q, r):
    dy = q[1] - p[1]
    L = abs(dy) or 1
    return q[1] - (r if dy > 0 else -r) * min(1.0, L / r) if abs(dy) > r else q[1]


# ------------------------------------------------------------------- validation
def _inside(px: float, py: float, rect, pad: float = 0.0) -> bool:
    l, t, r, b = rect
    return (l - pad) < px < (r + pad) and (t - pad) < py < (b + pad)


def validate() -> list[str]:
    errs: list[str] = []
    boxes = {k: box(k) for k in list(NODES) + ["bar"]}

    for k, (l, t, r, b) in boxes.items():
        if l < 0 or r > W or t < 0 or b > H:
            errs.append(f"{k}: box outside canvas ({l:.0f},{t:.0f})-({r:.0f},{b:.0f})")
    ids = list(boxes)
    for i, a in enumerate(ids):
        for b in ids[i + 1:]:
            al, at, ar, ab = boxes[a]
            bl, bt, br, bb = boxes[b]
            if al < br and bl < ar and at < bb and bt < ab:
                errs.append(f"{a} overlaps {b}")

    # text fit
    for k, n in NODES.items():
        w = MAIN_W if n["band"] == "main" else LEAF_W
        pad = 12 if n["band"] == "main" else 9
        name = n["name"]            # the step number lives in the corner badge
        if text_w(name, 12.5, bold=True) > w - pad:
            errs.append(f'{k}: name "{name}" too wide for a {w}px box')
        if text_w(n["tool"], 8.6) > w - pad:
            errs.append(f'{k}: tool line "{n["tool"]}" too wide ({text_w(n["tool"], 8.6):.0f}px)')
        for a in n["art"]:
            if text_w(a, 8.6, mono=True) > w - pad:
                errs.append(f'{k}: artifact line "{a}" too wide ({text_w(a, 8.6, mono=True):.0f}px)')

    # edges: endpoints on the right faces, and no point inside a foreign box
    for e in EDGES:
        for end in ("src", "dst"):
            if e[end] not in NODES and e[end] not in ("rail", "bar"):
                errs.append(f'edge {e["src"]}->{e["dst"]}: unknown node {e[end]}')
        if e["src"] in ("rail",) or e["dst"] == "rail":
            continue
        pts, _ = edge_path(e)
        skip = {e["src"], e["dst"]}
        for k, rect in boxes.items():
            if k in skip:
                continue
            for (px, py) in pts:
                if _inside(px, py, rect, pad=1.0):
                    errs.append(f'edge {e["src"]}->{e["dst"]} passes through {k} at '
                                f'({px:.0f},{py:.0f})')
                    break
    return errs


# ----------------------------------------------------------------- SVG emission
def esc(s: str) -> str:
    return s


def node_svg(k: str, n: dict) -> str:
    l, t, r, b = box(k)
    c = KIND[n.get("kind", "leaf" if n["band"] == "leaf" else "main")]
    cx = (l + r) / 2
    out = [
        f'<g class="pd-node">',
        f'<rect x="{l:g}" y="{t:g}" width="{r - l:g}" height="{b - t:g}" rx="9" '
        f'fill="{c["fill"]}" stroke="{c["stroke"]}" stroke-width="1.2"/>',
        f'<circle cx="{l + 17:g}" cy="{t + 17:g}" r="11" fill="#ffffff" opacity="0.94"/>',
        f'<text class="pd-step" x="{l + 17:g}" y="{t + 20.6:g}" fill="{c["fill"]}">'
        f'{n["step"]}</text>',
        f'<text class="pd-name" x="{cx:g}" y="{t + 40:g}" fill="{c["name"]}">{n["name"]}</text>',
        f'<text class="pd-tool" x="{cx:g}" y="{t + 55:g}" fill="{c["tool"]}">{n["tool"]}</text>',
        f'<line x1="{l + 16:g}" y1="{t + 63.5:g}" x2="{r - 16:g}" y2="{t + 63.5:g}" '
        f'stroke="{c["rule"]}" stroke-width="1"/>',
    ]
    ys = [t + 78, t + 91]
    for line, y in zip(n["art"], ys):
        out.append(f'<text class="pd-art" x="{cx:g}" y="{y:g}" fill="{c["art"]}">{line}</text>')
    out.append("</g>")
    return "".join(out)


def bar_svg() -> str:
    l, t, r, b = box("bar")
    c = KIND["collector"]
    cx = (l + r) / 2
    cy = (t + b) / 2
    m = MULTIQC
    return "".join([
        '<g class="pd-node">',
        f'<rect x="{l:g}" y="{t:g}" width="{r - l:g}" height="{b - t:g}" rx="10" '
        f'fill="{c["fill"]}" stroke="{c["stroke"]}" stroke-width="1.2"/>',
        f'<circle cx="{l + 26:g}" cy="{cy:g}" r="12.5" fill="#ffffff" opacity="0.94"/>',
        f'<text class="pd-step" x="{l + 26:g}" y="{cy + 4:g}" fill="{c["fill"]}">'
        f'{m["step"]}</text>',
        f'<text class="pd-name" x="{cx + 40:g}" y="{cy - 8:g}" fill="{c["name"]}" '
        f'text-anchor="middle">{m["name"]}</text>',
        f'<text class="pd-tool" x="{cx + 40:g}" y="{cy + 8:g}" fill="{c["tool"]}">'
        f'{m["tool"]}</text>',
        f'<text class="pd-art" x="{cx + 40:g}" y="{cy + 25:g}" fill="{c["art"]}">'
        f'{m["art"][0]}</text>',
        "</g>",
    ])


def label_svg(e: dict) -> str:
    if not e["label"]:
        return ""
    if e["kind"] == "report":
        return ""
    A, B = anchors(e["src"]), anchors(e["dst"])
    if abs(A["cy"] - B["cy"]) < 1:                 # horizontal edge: above the line
        x = (A["right"] + B["left"]) / 2
        y = A["cy"] - 9
        anchor = "middle"
    else:                                          # fork: above the target, offset left
        x = B["cx"] - 26
        y = B["top"] - 7
        anchor = "end"
    return (f'<text class="pd-elabel" x="{x:g}" y="{y:g}" text-anchor="{anchor}">'
            f'{e["label"]}</text>')


def edge_svg(e: dict) -> str:
    _, d = edge_path(e)
    if e["kind"] == "data":
        style = f'stroke="{KIND["main"]["fill"]}" stroke-width="1.6" marker-end="url(#pd-arw)"'
    elif e["kind"] == "order":
        style = ('stroke="#0f223d" stroke-width="1.5" stroke-dasharray="2 3" '
                 'marker-end="url(#pd-arw-sm)"')
    else:
        style = 'stroke="#178fa0" stroke-width="1.6" stroke-dasharray="5 4"' + (
            ' marker-end="url(#pd-arw-teal)"' if e["dst"] == "bar" else "")
    cls = "pd-opt" if NODES.get(e["src"], {}).get("kind") == "optional" else ""
    return f'<path class="{cls}" d="{d}" fill="none" stroke-linecap="round" {style}/>'


def rail_svg() -> str:
    """The report-input bus, with a dot at every junction."""
    xs = [anchors(k)["cx"] for k in ("fq_raw", "fq_trim", "quast", "refcmp", "busco",
                                    "growth", "memote")]
    lo, hi = min(xs), bar_left()
    dots = "".join(f'<circle cx="{x:g}" cy="{RAIL_Y}" r="2.4" fill="#178fa0"/>' for x in xs)
    dots += f'<circle cx="{bar_drop_x():g}" cy="{RAIL_Y}" r="2.4" fill="#178fa0"/>'
    return (f'<line x1="{lo:g}" y1="{RAIL_Y}" x2="{hi:g}" y2="{RAIL_Y}" '
            f'stroke="#178fa0" stroke-width="1.6" stroke-dasharray="5 4"/>' + dots)


def bar_drop_x() -> float:
    return 700


